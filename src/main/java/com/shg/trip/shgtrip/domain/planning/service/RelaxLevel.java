package com.shg.trip.shgtrip.domain.planning.service;

/**
 * 모든 필터를 AND로만 걸면 필수 슬롯(식사·숙소) 후보가 하나도 안 남는 날이 생겨 단계적으로 푼다.
 * 정기휴무·식사적합처럼 틀린 결과를 만드는 조건은 끝까지 유지한다.
 */
enum RelaxLevel {
    /** 반경·거리예산 모두 적용. */
    L1,
    /** 반경 2배. 거리 예산은 유지. */
    L2,
    /** 반경 무제한 + 거리 예산 해제. 휴무·적합성만 본다. */
    L3
}
